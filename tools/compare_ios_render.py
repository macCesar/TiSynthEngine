#!/usr/bin/env python3
"""Compare actual Apple renderer PCM and semantic snapshots byte-for-byte.

Stream traces through bounded pipes; no multi-gigabyte trace files are retained.
Use --trace host binaries generated by build_ios_render_host.py. This runs no
timing benchmark: concurrent processes are deliberate for sample comparison only.
"""
import argparse
import json
from pathlib import Path
import subprocess


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("baseline", type=Path)
    p.add_argument("candidate", type=Path)
    p.add_argument("--pcm-only",action="store_true",help="Compare PCM only when internal structure layouts differ")
    args = p.parse_args()
    processes = [subprocess.Popen([str(binary), "--pcm-trace" if args.pcm_only else "--trace"], stdout=subprocess.PIPE)
                 for binary in [args.baseline, args.candidate]]
    count = 0
    try:
        while True:
            a, b = [process.stdout.read(1024 * 1024) for process in processes]
            if a != b:
                offset = next((i for i, pair in enumerate(zip(a, b)) if pair[0] != pair[1]), min(len(a), len(b)))
                raise SystemExit("Apple renderer trace differs at byte " + str(count + offset))
            count += len(a)
            if not a:
                break
        assert all(process.wait() == 0 for process in processes), "Renderer failed"
        print(json.dumps({"byteExact": True, "comparedBytes": count, "scenarios": 120, "pcmOnly": args.pcm_only,
                          "scope": "PCM for every fixture block; state checkpoints included only without --pcm-only. No hardware/session acceptance"}))
    finally:
        for process in processes:
            if process.poll() is None:
                process.terminate()
            process.wait()


if __name__ == "__main__":
    main()
